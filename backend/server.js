app.post('/api/auth/login', (req, res) => {
  const email    = String(req.body?.email || '').trim();
  const password = String(req.body?.password || '');

  const configuredEmail    = process.env.ADMIN_EMAIL || '';
  const configuredPassword = process.env.ADMIN_PASSWORD || '';

  if (!configuredEmail || !configuredPassword) {
    return res.status(500).json({ success: false, error: 'Server authentication is not configured.' });
  }

  if (hash(email) !== hash(configuredEmail) || hash(password) !== hash(configuredPassword)) {
    return res.status(401).json({ success: false, error: 'Invalid email or password.' });
  }

  const token = crypto.randomBytes(32).toString('hex');
  sessions.set(token, { createdAt: Date.now(), expiresAt: Date.now() + SESSION_TTL_MS });

  res.cookie('voxora_session', token, {
    httpOnly: true,
    sameSite: 'lax',
    secure: process.env.NODE_ENV === 'production',
    maxAge: SESSION_TTL_MS,
    path: '/'
  });

  return res.json({ success: true });
});

