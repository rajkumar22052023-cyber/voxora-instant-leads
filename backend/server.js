app.put('/api/instant-clients/:clientId', requireAuth, async (req, res) => {
  if (!requireConfig(res)) return;

  const clientId = String(req.params.clientId || '').trim();
  if (!clientId)         return res.status(400).json({ success: false, error: 'Client ID is required.' });
  if (!isValidUUID(clientId)) return res.status(400).json({ success: false, error: 'Invalid client ID. The client must use its Supabase UUID.' });

  const body = req.body || {};

  // Accept agent_id and from_number_id as plain strings (text columns).
  // Also tolerate the legacy omnidimension_* field names the frontend may send.
  const clientName   = typeof body.client_name === 'string' ? body.client_name.trim() : '';
  const agentId      = String(body.agent_id ?? body.omnidimension_agent_id ?? '').trim();
  const fromNumberId = String(body.from_number_id ?? body.omnidimension_from_number_id ?? '').trim();
  const source       = typeof body.source === 'string' ? body.source.trim() : null;

  if (!clientName || !agentId || !fromNumberId) {
    return res.status(400).json({
      success: false,
      error: 'client_name, agent_id, and from_number_id are required.'
    });
  }

  try {
    // Verify the client exists first.
    const { data: existingClient, error: existingError } = await supabase
      .from('instant_clients')
      .select('id')
      .eq(column.id, clientId)
      .maybeSingle();

    if (existingError) return res.status(500).json({ success: false, error: 'Failed to find client before update.', details: existingError.message });
    if (!existingClient) return res.status(404).json({ success: false, error: 'Client not found.' });

    const update = {
      [column.name]:       clientName,
      [column.agent]:      agentId,        // text, no conversion
      [column.fromNumber]: fromNumberId,   // text, no conversion
      updated_at: new Date().toISOString()
    };
    if (source !== null) update[column.source] = source;

    const { error: updateError } = await supabase
      .from('instant_clients')
      .update(update)
      .eq(column.id, clientId);

    if (updateError) {
      console.error('SUPABASE UPDATE ERROR:', updateError);
      return res.status(500).json({
        success: false,
        error: 'Supabase update failed.',
        details: updateError.message,
        code: updateError.code || null,
        hint: updateError.hint || null,
        details_from_supabase: updateError.details || null
      });
    }

    // Read the updated row back.
    const { data, error: readError } = await supabase
      .from('instant_clients')
      .select('*')
      .eq(column.id, clientId)
      .maybeSingle();

    if (readError) return res.status(500).json({ success: false, error: 'Client updated, but failed to read the updated client.', details: readError.message });
    if (!data)     return res.status(404).json({ success: false, error: 'Client not found after update.' });

    return res.json({ success: true, client: data });
  } catch (err) {
    console.error('CLIENT UPDATE EXCEPTION:', err);
    return res.status(500).json({ success: false, error: 'Backend exception.', details: err?.message || String(err) });
  }
});

