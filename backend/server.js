/* =========================================================
   PUBLIC INSTANT LEAD INGESTION + OMNIDIMENSION DISPATCH
========================================================= */

app.post('/instant-lead/:token', async (req, res) => {
  if (!requireConfig(res)) return;

  const token = String(req.params.token || '').trim();

  if (!token) {
    return res.status(400).json({
      success: false,
      error: 'Integration token is required.'
    });
  }

  const formData =
    req.body && typeof req.body === 'object'
      ? req.body
      : {};

  const phone = String(
    formData.phone ??
    formData.phone_number ??
    formData.mobile ??
    formData.mobile_number ??
    ''
  ).trim();

  const customerName = String(
    formData.customer_name ??
    formData.name ??
    ''
  ).trim();

  if (!phone) {
    return res.status(400).json({
      success: false,
      error: 'Customer phone number is required.'
    });
  }

  try {
    /* -------------------------------------------------------
       1. FIND INTEGRATION
    ------------------------------------------------------- */

    const {
      data: integration,
      error: integrationError
    } = await supabase
      .from('instant_integrations')
      .select('*')
      .eq('integration_token', token)
      .eq('is_active', true)
      .maybeSingle();

    if (integrationError) {
      console.error(
        'INSTANT LEAD INTEGRATION LOOKUP ERROR:',
        integrationError
      );

      return res.status(500).json({
        success: false,
        error: 'Failed to find integration.',
        details: integrationError.message
      });
    }

    if (!integration) {
      return res.status(404).json({
        success: false,
        error: 'Invalid or inactive integration token.'
      });
    }

    /* -------------------------------------------------------
       2. FIND CLIENT
    ------------------------------------------------------- */

    const {
      data: client,
      error: clientError
    } = await supabase
      .from('instant_clients')
      .select('*')
      .eq('id', integration.client_id)
      .maybeSingle();

    if (clientError) {
      console.error(
        'INSTANT LEAD CLIENT LOOKUP ERROR:',
        clientError
      );

      return res.status(500).json({
        success: false,
        error: 'Failed to find client.',
        details: clientError.message
      });
    }

    if (!client) {
      return res.status(404).json({
        success: false,
        error:
          'Client associated with this integration was not found.'
      });
    }

    /* -------------------------------------------------------
       3. PRESERVE ALL FORM DATA
    ------------------------------------------------------- */

    const rawFormData = { ...formData };

    const customData = {
      ...formData
    };

    /* -------------------------------------------------------
       4. CREATE LEAD
    ------------------------------------------------------- */

    const {
      data: lead,
      error: leadError
    } = await supabase
      .from('instant_leads')
      .insert({
        client_id: client.id,
        integration_id: integration.id,
        customer_name: customerName || null,
        phone,
        custom_data: customData,
        raw_form_data: rawFormData,
        call_status: 'pending'
      })
      .select('*')
      .single();

    if (leadError) {
      console.error(
        'INSTANT LEAD INSERT ERROR:',
        leadError
      );

      return res.status(500).json({
        success: false,
        error: 'Failed to save lead.',
        details: leadError.message,
        code: leadError.code || null,
        hint: leadError.hint || null
      });
    }

    /* -------------------------------------------------------
       5. BUILD DYNAMIC CALL CONTEXT
    ------------------------------------------------------- */

    const callContext = {
      ...customData
    };

    /* -------------------------------------------------------
       6. READ CLIENT OMNIDIMENSION IDS
    ------------------------------------------------------- */

    const rawAgentId =
      client.agent_id ??
      client.omnidimension_agent_id ??
      '';

    const rawFromNumberId =
      client.from_number_id ??
      client.omnidimension_from_number_id ??
      '';

    const agentIdText = String(
      rawAgentId ?? ''
    ).trim();

    const fromNumberIdText = String(
      rawFromNumberId ?? ''
    ).trim();

    const agentId =
      /^\d+$/.test(agentIdText)
        ? Number(agentIdText)
        : NaN;

    const fromNumberId =
      /^\d+$/.test(fromNumberIdText)
        ? Number(fromNumberIdText)
        : NaN;

    /* -------------------------------------------------------
       7. CHECK OMNIDIMENSION CONFIGURATION
    ------------------------------------------------------- */

    if (
      !Number.isSafeInteger(agentId) ||
      !Number.isSafeInteger(fromNumberId)
    ) {
      const pendingReason =
        !Number.isSafeInteger(agentId)
          ? 'OmniDimension agent_id is not configured as a valid numeric ID.'
          : 'OmniDimension from_number_id is not configured as a valid numeric ID.';

      await supabase
        .from('instant_leads')
        .update({
          call_status: 'pending',
          error_message: pendingReason,
          updated_at: new Date().toISOString()
        })
        .eq('id', lead.id);

      return res.status(201).json({
        success: true,
        lead_id: lead.id,
        client_id: client.id,
        client_name: client.client_name,
        integration_id: integration.id,
        call_status: 'pending',
        dispatch: 'waiting_for_omnidimension_configuration'
      });
    }

    /* -------------------------------------------------------
       8. CHECK API KEY
    ------------------------------------------------------- */

    const omniApiKey =
      String(
        process.env.OMNIDIM_API_KEY || ''
      ).trim();

    if (!omniApiKey) {
      const errorMessage =
        'OMNIDIM_API_KEY is not configured.';

      await supabase
        .from('instant_leads')
        .update({
          call_status: 'pending',
          error_message: errorMessage,
          updated_at: new Date().toISOString()
        })
        .eq('id', lead.id);

      return res.status(201).json({
        success: true,
        lead_id: lead.id,
        client_id: client.id,
        client_name: client.client_name,
        integration_id: integration.id,
        call_status: 'pending',
        dispatch: 'waiting_for_api_key'
      });
    }

    /* -------------------------------------------------------
       9. MARK DISPATCHING
    ------------------------------------------------------- */

    await supabase
      .from('instant_leads')
      .update({
        call_status: 'dispatching',
        error_message: null,
        updated_at: new Date().toISOString()
      })
      .eq('id', lead.id);

    /* -------------------------------------------------------
       10. DISPATCH OMNIDIMENSION CALL
    ------------------------------------------------------- */

    const dispatchPayload = {
      agent_id: agentId,
      to_number: phone,
      from_number_id: fromNumberId,
      call_context: callContext,
      metadata: {
        voxora_lead_id: lead.id,
        client_id: client.id,
        integration_id: integration.id,
        integration_token: token,
        source: client.source || 'Website Form'
      }
    };

    console.log(
      'OMNIDIMENSION DISPATCH REQUEST:',
      {
        agent_id: agentId,
        from_number_id: fromNumberId,
        to_number: phone,
        lead_id: lead.id
      }
    );

    const omniResponse = await fetch(
      'https://backend.omnidim.io/api/v1/calls/dispatch',
      {
        method: 'POST',
        headers: {
          'Authorization': `Bearer ${omniApiKey}`,
          'Content-Type': 'application/json'
        },
        body: JSON.stringify(dispatchPayload)
      }
    );

    const omniResult =
      await omniResponse
        .json()
        .catch(() => ({}));

    console.log(
      'OMNIDIMENSION DISPATCH RESPONSE:',
      omniResponse.status,
      omniResult
    );

    /* -------------------------------------------------------
       11. HANDLE DISPATCH FAILURE
    ------------------------------------------------------- */

    if (
      !omniResponse.ok ||
      !omniResult.success
    ) {
      const errorMessage =
        omniResult.error_description ||
        omniResult.error ||
        omniResult.message ||
        `OmniDimension dispatch failed with HTTP ${omniResponse.status}.`;

      await supabase
        .from('instant_leads')
        .update({
          call_status: 'failed',
          error_message: errorMessage,
          updated_at: new Date().toISOString()
        })
        .eq('id', lead.id);

      return res.status(201).json({
        success: true,
        lead_id: lead.id,
        client_id: client.id,
        client_name: client.client_name,
        integration_id: integration.id,
        call_status: 'failed',
        error: errorMessage
      });
    }

    /* -------------------------------------------------------
       12. SAVE DISPATCH RESULT
    ------------------------------------------------------- */

    const requestId =
      omniResult.requestId ??
      omniResult.request_id ??
      null;

    const callId =
      omniResult.callId ??
      omniResult.call_id ??
      null;

    await supabase
      .from('instant_leads')
      .update({
        call_status: 'dispatched',
        omnidim_request_id:
          requestId !== null
            ? String(requestId)
            : null,
        omnidim_call_id:
          callId !== null
            ? String(callId)
            : null,
        error_message: null,
        updated_at: new Date().toISOString()
      })
      .eq('id', lead.id);

    /* -------------------------------------------------------
       13. SUCCESS RESPONSE
    ------------------------------------------------------- */

    return res.status(201).json({
      success: true,
      lead_id: lead.id,
      client_id: client.id,
      client_name: client.client_name,
      integration_id: integration.id,
      call_status: 'dispatched',
      omnidim_request_id: requestId,
      omnidim_call_id: callId
    });

  } catch (err) {
    console.error(
      'INSTANT LEAD ERROR:',
      err
    );

    return res.status(500).json({
      success: false,
      error: 'Instant Lead processing failed.',
      details: err?.message || String(err)
    });
  }
});

