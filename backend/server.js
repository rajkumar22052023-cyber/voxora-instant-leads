app.post('/api/instant-clients', requireAuth, async (req, res) => {
  if (!requireConfig(res)) return;

  const body = req.body || {};

  const clientName =
    typeof body.client_name === 'string'
      ? body.client_name.trim()
      : '';

  const agentId =
    typeof body.agent_id === 'string'
      ? body.agent_id.trim()
      : String(body.agent_id || '').trim();

  const fromNumberId =
    typeof body.from_number_id === 'string'
      ? body.from_number_id.trim()
      : String(body.from_number_id || '').trim();

  const source =
    typeof body.source === 'string' && body.source.trim()
      ? body.source.trim()
      : 'Website Form';

  const integrationToken =
    typeof body.integration_token === 'string' &&
    body.integration_token.trim()
      ? body.integration_token.trim()
      : 'il_' + crypto.randomBytes(10).toString('hex');

  if (!clientName || !agentId || !fromNumberId) {
    return res.status(400).json({
      success: false,
      error:
        'client_name, agent_id, and from_number_id are required.'
    });
  }

  try {
    /* -------------------------------------------------------
       1. CREATE CLIENT
    ------------------------------------------------------- */

    const insert = {
      [column.name]: clientName,
      [column.agent]: agentId,
      [column.fromNumber]: fromNumberId,
      [column.source]: source,
      [column.integrationToken]: integrationToken,
      [column.isActive]: true,
      updated_at: new Date().toISOString()
    };

    const {
      data: client,
      error: clientError
    } = await supabase
      .from('instant_clients')
      .insert(insert)
      .select('*')
      .single();

    if (clientError) {
      console.error('SUPABASE CLIENT INSERT ERROR:', clientError);

      return res.status(500).json({
        success: false,
        error: 'Supabase client insert failed.',
        details: clientError.message,
        code: clientError.code || null,
        hint: clientError.hint || null
      });
    }

    /* -------------------------------------------------------
       2. CREATE LINKED INTEGRATION
    ------------------------------------------------------- */

    const {
      data: integration,
      error: integrationError
    } = await supabase
      .from('instant_integrations')
      .insert({
        client_id: client.id,
        integration_token: integrationToken,
        integration_name: `${clientName} Instant Lead`,
        is_active: true
      })
      .select('*')
      .single();

    if (integrationError) {
      console.error(
        'SUPABASE INTEGRATION INSERT ERROR:',
        integrationError
      );

      /*
       * IMPORTANT:
       * If the integration cannot be created, remove the
       * client we just created so we don't leave an orphan
       * client without an integration.
       */
      await supabase
        .from('instant_clients')
        .delete()
        .eq('id', client.id);

      return res.status(500).json({
        success: false,
        error: 'Failed to create client integration.',
        details: integrationError.message,
        code: integrationError.code || null,
        hint: integrationError.hint || null
      });
    }

    /* -------------------------------------------------------
       3. RETURN BOTH RECORDS
    ------------------------------------------------------- */

    return res.status(201).json({
      success: true,
      client,
      integration
    });

  } catch (err) {
    console.error('CLIENT CREATE EXCEPTION:', err);

    return res.status(500).json({
      success: false,
      error: 'Backend exception.',
      details: err?.message || String(err)
    });
  }
});
